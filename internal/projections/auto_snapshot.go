package projections

import (
	"context"
	"database/sql"
	"encoding/json"
	"errors"

	"DebtEase/internal/database"

	"github.com/google/uuid"
)

// mergeSnapshotExtra preserves snapshot JSON extras and refreshes active_debt_count from live debts.
func mergeSnapshotExtra(prev json.RawMessage, activeDebtCount int) json.RawMessage {
	var m map[string]interface{}
	if len(prev) > 0 {
		_ = json.Unmarshal(prev, &m)
	}
	if m == nil {
		m = make(map[string]interface{})
	}
	m["active_debt_count"] = activeDebtCount
	out, err := json.Marshal(m)
	if err != nil {
		return prev
	}
	return out
}

// RegenerateAutoGeneratedFinancialSnapshot inserts a new financial_snapshots row aligned with live debt aggregates,
// preserving income/expense/asset fields from the user's latest snapshot. No-op if the user has no prior snapshot.
func RegenerateAutoGeneratedFinancialSnapshot(ctx context.Context, q *database.Queries, userID uuid.UUID, triggerEvent string) error {
	prev, err := q.GetLatestSnapshotByUser(ctx, uuid.NullUUID{UUID: userID, Valid: true})
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil
		}
		return err
	}

	rollup, err := q.GetPortfolioRollupForUser(ctx, userID)
	if err != nil {
		return err
	}

	extra := mergeSnapshotExtra(prev.ExtraData, int(rollup.ActiveDebtCount))

	_, err = q.InsertAutoGeneratedFinancialSnapshot(ctx, database.InsertAutoGeneratedFinancialSnapshotParams{
		UserID:           uuid.NullUUID{UUID: userID, Valid: true},
		SessionID:        uuid.NullUUID{},
		SnapshotType:     "auto_generated",
		SnapshotSource:   "calculated",
		MonthlyIncome:    prev.MonthlyIncome,
		OtherIncome:      prev.OtherIncome,
		FixedExpenses:    prev.FixedExpenses,
		VariableExpenses: prev.VariableExpenses,
		SavingsCash:      prev.SavingsCash,
		InvestmentsValue: prev.InvestmentsValue,
		TotalMonthlyEmi:  rollup.TotalMonthlyEmi,
		TotalDebtBalance: rollup.TotalDebtBalance,
		DependentsCount:  prev.DependentsCount,
		TriggerEvent:     sql.NullString{String: triggerEvent, Valid: triggerEvent != ""},
		SnapshotVersion:  prev.SnapshotVersion + 1,
		ExtraData:        extra,
	})
	return err
}
