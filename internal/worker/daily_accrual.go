package worker

import (
	"context"
	"database/sql"
	"time"

	"DebtEase/internal/database"
	financial_events "DebtEase/internal/domain/financial_events/v1"
	"DebtEase/internal/ledger"
	"DebtEase/internal/logger"
	"DebtEase/internal/projections"

	"github.com/shopspring/decimal"
)

func StartDailyAccrual(ctx context.Context, pool *sql.DB, q *database.Queries, tick time.Duration) {
	if tick <= 0 {
		tick = 24 * time.Hour
	}
	ticker := time.NewTicker(tick)
	go func() {
		defer ticker.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case t := <-ticker.C:
				processAccrual(ctx, pool, q, t)
			}
		}
	}()
}

func processAccrual(ctx context.Context, pool *sql.DB, q *database.Queries, now time.Time) {
	today := time.Date(now.Year(), now.Month(), now.Day(), 0, 0, 0, 0, time.UTC)

	creditCards, err := q.ListCreditCardsOutOfGrace(ctx)
	if err != nil {
		logger.Logger.Errorw("ListCreditCardsOutOfGrace failed", "error", err)
		return
	}

	for _, cc := range creditCards {
		last := cc.LastAccrualDate
		lastDate := time.Date(last.Year(), last.Month(), last.Day(), 0, 0, 0, 0, time.UTC)

		days := int(today.Sub(lastDate).Hours() / 24)
		if days <= 0 {
			continue
		}

		dailyRate := cc.InterestRate.Div(decimal.NewFromInt(36500))
		delta := cc.OutstandingBalance.Mul(dailyRate).Mul(decimal.NewFromInt(int64(days)))

		tx, err := pool.BeginTx(ctx, nil)
		if err != nil {
			logger.Logger.Errorw("BeginTx daily accrual failed", "error", err)
			continue
		}
		qw := q.WithTx(tx)

		if err := qw.AccrueInterest(ctx, database.AccrueInterestParams{
			ID:              cc.DebtID,
			AccruedInterest: delta,
			LastAccrualDate: today,
		}); err != nil {
			logger.Logger.Errorw("AccrueInterest failed", "debt_id", cc.DebtID, "error", err)
			_ = tx.Rollback()
			continue
		}

		if err := qw.AddDailyInterestToUnbilled(ctx, database.AddDailyInterestToUnbilledParams{
			DebtID:          cc.DebtID,
			UnbilledBalance: delta,
		}); err != nil {
			logger.Logger.Errorw("AddDailyInterestToUnbilled failed", "debt_id", cc.DebtID, "error", err)
			_ = tx.Rollback()
			continue
		}

		meta := map[string]interface{}{
			financial_events.MetaInterestDelta: delta.StringFixed(2),
		}
		d := delta
		if err := ledger.Append(ctx, qw, ledger.Params{
			UserID:     cc.UserID,
			EventType:  financial_events.EventInterestAccrued,
			EntityType: financial_events.EntityDebt,
			EntityID:   cc.DebtID,
			Amount:     &d,
			OccurredAt: today,
			Metadata:   meta,
		}); err != nil {
			logger.Logger.Errorw("ledger append interest accrual failed", "error", err)
			_ = tx.Rollback()
			continue
		}
		if err := projections.RegenerateAutoGeneratedFinancialSnapshot(ctx, qw, cc.UserID, financial_events.EventInterestAccrued); err != nil {
			logger.Logger.Errorw("snapshot regenerate interest accrual failed", "error", err)
			_ = tx.Rollback()
			continue
		}
		if err := tx.Commit(); err != nil {
			logger.Logger.Errorw("Commit daily accrual failed", "error", err)
			continue
		}
	}
}
