package worker

import (
	"context"
	"database/sql"
	"time"

	"DebtEase/internal/database"
	financial_events "DebtEase/internal/domain/financial_events/v1"
	"DebtEase/internal/ledger"
	"DebtEase/internal/logger"
	"DebtEase/internal/projections"
)

// ProcessCreditCardStatements generates monthly statements for credit cards on their billing day.
func ProcessCreditCardStatements(ctx context.Context, pool *sql.DB, q *database.Queries) {
	cards, err := q.ListCreditCardsNeedingStatement(ctx)
	if err != nil {
		logger.Logger.Errorw("ListCreditCardsNeedingStatement failed", "error", err)
		return
	}

	today := time.Date(time.Now().Year(), time.Now().Month(), time.Now().Day(), 0, 0, 0, 0, time.UTC)

	for _, card := range cards {
		paymentDueDate := today.AddDate(0, 0, int(card.GracePeriodDays))

		tx, err := pool.BeginTx(ctx, nil)
		if err != nil {
			logger.Logger.Errorw("BeginTx statement worker failed", "error", err)
			continue
		}
		qw := q.WithTx(tx)

		err = qw.GenerateStatement(ctx, database.GenerateStatementParams{
			DebtID:            card.DebtID,
			LastStatementDate: sql.NullTime{Time: today, Valid: true},
			PaymentDueDate:    sql.NullTime{Time: paymentDueDate, Valid: true},
		})

		if err != nil {
			logger.Logger.Errorw("GenerateStatement failed",
				"debt_id", card.DebtID,
				"card_name", card.Name,
				"error", err)
			_ = tx.Rollback()
			continue
		}

		meta := map[string]interface{}{
			financial_events.MetaDebtID: card.DebtID.String(),
			"billing_day":               card.BillingDay,
			"payment_due_date":          paymentDueDate.Format("2006-01-02"),
		}
		if err := ledger.Append(ctx, qw, ledger.Params{
			UserID:     card.UserID,
			EventType:  financial_events.EventStatementCycleAdvanced,
			EntityType: financial_events.EntityDebt,
			EntityID:   card.DebtID,
			OccurredAt: today,
			Metadata:   meta,
		}); err != nil {
			logger.Logger.Errorw("ledger append statement cycle failed", "error", err)
			_ = tx.Rollback()
			continue
		}
		if err := projections.RegenerateAutoGeneratedFinancialSnapshot(ctx, qw, card.UserID, financial_events.EventStatementCycleAdvanced); err != nil {
			logger.Logger.Errorw("snapshot regenerate statement cycle failed", "error", err)
			_ = tx.Rollback()
			continue
		}
		if err := tx.Commit(); err != nil {
			logger.Logger.Errorw("Commit statement cycle failed", "error", err)
			continue
		}

		logger.Logger.Infow("Credit card statement generated",
			"debt_id", card.DebtID,
			"card_name", card.Name,
			"billing_day", card.BillingDay,
			"payment_due_date", paymentDueDate.Format("2006-01-02"))
	}
}

// StartCreditCardStatementWorker starts a worker that runs daily to generate statements.
func StartCreditCardStatementWorker(ctx context.Context, pool *sql.DB, q *database.Queries, tick time.Duration) {
	if tick <= 0 {
		tick = 24 * time.Hour
	}
	ticker := time.NewTicker(tick)
	go func() {
		defer ticker.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				ProcessCreditCardStatements(ctx, pool, q)
			}
		}
	}()
}
