package worker

import (
	"context"
	"database/sql"
	"time"

	"DebtEase/internal/database"
	financial_events "DebtEase/internal/domain/financial_events/v1"
	"DebtEase/internal/ledger"
	"DebtEase/internal/logger"
	"DebtEase/internal/projections"

	"github.com/shopspring/decimal"
)

// ProcessLoanEMI handles EMI accrual and moratorium for loans on their due day.
func ProcessLoanEMI(ctx context.Context, pool *sql.DB, q *database.Queries) {
	loans, err := q.ListLoansNeedingEMI(ctx)
	if err != nil {
		logger.Logger.Errorw("ListLoansNeedingEMI failed", "error", err)
		return
	}

	today := time.Date(time.Now().Year(), time.Now().Month(), time.Now().Day(), 0, 0, 0, 0, time.UTC)

	for _, loan := range loans {
		if loan.OutstandingBalance.LessThanOrEqual(decimal.Zero) {
			continue
		}

		tx, err := pool.BeginTx(ctx, nil)
		if err != nil {
			logger.Logger.Errorw("BeginTx loan EMI failed", "error", err)
			continue
		}
		qw := q.WithTx(tx)

		userID := loan.UserID

		if loan.InMoratorium.Valid && loan.InMoratorium.Bool {
			if loan.MoratoriumUntil.Valid && today.After(loan.MoratoriumUntil.Time) {
				remainingMonths := int32(0)
				if loan.RemainingMonths.Valid {
					remainingMonths = loan.RemainingMonths.Int32
				}

				if remainingMonths > 0 {
					emi := calculateEMI(loan.OutstandingBalance, loan.InterestRate, int(remainingMonths))

					err := qw.ExitMoratorium(ctx, database.ExitMoratoriumParams{
						ID:                loan.ID,
						MonthlyObligation: emi,
					})

					if err != nil {
						logger.Logger.Errorw("ExitMoratorium failed",
							"debt_id", loan.ID,
							"loan_name", loan.Name,
							"error", err)
						_ = tx.Rollback()
						continue
					}

					meta := map[string]interface{}{
						financial_events.MetaDebtID: loan.ID.String(),
						financial_events.MetaNewEMI: emi.StringFixed(2),
					}
					if err := ledger.Append(ctx, qw, ledger.Params{
						UserID:     userID,
						EventType:  financial_events.EventLoanMoratoriumExited,
						EntityType: financial_events.EntityDebt,
						EntityID:   loan.ID,
						OccurredAt: today,
						Metadata:   meta,
					}); err != nil {
						logger.Logger.Errorw("ledger append loan moratorium exit failed", "error", err)
						_ = tx.Rollback()
						continue
					}
					if err := projections.RegenerateAutoGeneratedFinancialSnapshot(ctx, qw, userID, financial_events.EventLoanMoratoriumExited); err != nil {
						logger.Logger.Errorw("snapshot regenerate loan moratorium exit failed", "error", err)
						_ = tx.Rollback()
						continue
					}
					if err := tx.Commit(); err != nil {
						logger.Logger.Errorw("Commit loan moratorium exit failed", "error", err)
						continue
					}

					logger.Logger.Infow("Loan exited moratorium",
						"debt_id", loan.ID,
						"loan_name", loan.Name,
						"new_emi", emi.String(),
						"remaining_months", remainingMonths)
				} else {
					_ = tx.Rollback()
				}
				continue
			}

			monthlyRate := loan.InterestRate.Div(decimal.NewFromInt(1200))
			interest := loan.OutstandingBalance.Mul(monthlyRate)
			newBalance := loan.OutstandingBalance.Add(interest)

			err := qw.UpdateDebtAfterPayment(ctx, database.UpdateDebtAfterPaymentParams{
				ID:                 loan.ID,
				OutstandingBalance: newBalance,
				AccruedInterest:    decimal.Zero,
				LastAccrualDate:    today,
			})

			if err != nil {
				logger.Logger.Errorw("Capitalize moratorium interest failed",
					"debt_id", loan.ID,
					"loan_name", loan.Name,
					"error", err)
				_ = tx.Rollback()
				continue
			}

			meta := map[string]interface{}{
				financial_events.MetaInterestDelta: interest.StringFixed(2),
			}
			if err := ledger.Append(ctx, qw, ledger.Params{
				UserID:     userID,
				EventType:  financial_events.EventMoratoriumInterestCapitalized,
				EntityType: financial_events.EntityDebt,
				EntityID:   loan.ID,
				Amount:     &interest,
				OccurredAt: today,
				Metadata:   meta,
			}); err != nil {
				logger.Logger.Errorw("ledger append moratorium capitalize failed", "error", err)
				_ = tx.Rollback()
				continue
			}
			if err := projections.RegenerateAutoGeneratedFinancialSnapshot(ctx, qw, userID, financial_events.EventMoratoriumInterestCapitalized); err != nil {
				logger.Logger.Errorw("snapshot regenerate moratorium capitalize failed", "error", err)
				_ = tx.Rollback()
				continue
			}
			if err := tx.Commit(); err != nil {
				logger.Logger.Errorw("Commit moratorium capitalize failed", "error", err)
				continue
			}

			logger.Logger.Infow("Moratorium interest capitalized",
				"debt_id", loan.ID,
				"loan_name", loan.Name,
				"interest", interest.String(),
				"new_balance", newBalance.String())
			continue
		}

		monthlyRate := loan.InterestRate.Div(decimal.NewFromInt(1200))
		interestComponent := loan.OutstandingBalance.Mul(monthlyRate)

		emiAmount := loan.MonthlyObligation
		if emiAmount.IsZero() {
			logger.Logger.Warnw("Loan has no monthly obligation set",
				"debt_id", loan.ID,
				"loan_name", loan.Name)
			_ = tx.Rollback()
			continue
		}

		principalComponent := emiAmount.Sub(interestComponent)

		if principalComponent.GreaterThanOrEqual(loan.OutstandingBalance) {
			principalComponent = loan.OutstandingBalance
		}

		newBalance := loan.OutstandingBalance.Sub(principalComponent)
		if newBalance.IsNegative() {
			newBalance = decimal.Zero
		}

		err = qw.UpdateDebtAfterPayment(ctx, database.UpdateDebtAfterPaymentParams{
			ID:                 loan.ID,
			OutstandingBalance: newBalance,
			AccruedInterest:    decimal.Zero,
			LastAccrualDate:    today,
		})

		if err != nil {
			logger.Logger.Errorw("UpdateDebtAfterPayment failed",
				"debt_id", loan.ID,
				"loan_name", loan.Name,
				"error", err)
			_ = tx.Rollback()
			continue
		}

		err = qw.DecrementRemainingMonthsAfterEMI(ctx, loan.ID)
		if err != nil {
			logger.Logger.Errorw("DecrementRemainingMonthsAfterEMI failed",
				"debt_id", loan.ID,
				"loan_name", loan.Name,
				"error", err)
			_ = tx.Rollback()
			continue
		}

		meta := map[string]interface{}{
			financial_events.MetaPrincipalComponent: principalComponent.StringFixed(2),
			financial_events.MetaInterestComponent:  interestComponent.StringFixed(2),
		}
		amt := emiAmount
		if err := ledger.Append(ctx, qw, ledger.Params{
			UserID:     userID,
			EventType:  financial_events.EventEMIAutopApplied,
			EntityType: financial_events.EntityDebt,
			EntityID:   loan.ID,
			Amount:     &amt,
			OccurredAt: today,
			Metadata:   meta,
		}); err != nil {
			logger.Logger.Errorw("ledger append EMI autop failed", "error", err)
			_ = tx.Rollback()
			continue
		}
		if err := projections.RegenerateAutoGeneratedFinancialSnapshot(ctx, qw, userID, financial_events.EventEMIAutopApplied); err != nil {
			logger.Logger.Errorw("snapshot regenerate EMI autop failed", "error", err)
			_ = tx.Rollback()
			continue
		}
		if err := tx.Commit(); err != nil {
			logger.Logger.Errorw("Commit EMI autop failed", "error", err)
			continue
		}

		logger.Logger.Infow("Loan EMI processed",
			"debt_id", loan.ID,
			"loan_name", loan.Name,
			"emi", emiAmount.String(),
			"interest", interestComponent.String(),
			"principal", principalComponent.String(),
			"new_balance", newBalance.String())
	}
}

// calculateEMI calculates EMI using reducing balance formula.
func calculateEMI(principal, annualRate decimal.Decimal, months int) decimal.Decimal {
	if months == 0 {
		return decimal.Zero
	}

	monthlyRate := annualRate.Div(decimal.NewFromInt(1200))

	if monthlyRate.IsZero() {
		return principal.Div(decimal.NewFromInt(int64(months)))
	}

	onePlusR := decimal.NewFromInt(1).Add(monthlyRate)
	onePlusRPowN := onePlusR.Pow(decimal.NewFromInt(int64(months)))

	numerator := principal.Mul(monthlyRate).Mul(onePlusRPowN)
	denominator := onePlusRPowN.Sub(decimal.NewFromInt(1))

	emi := numerator.Div(denominator)
	return emi.Round(2)
}

// StartLoanEMIWorker starts a worker that runs daily to process loan EMIs.
func StartLoanEMIWorker(ctx context.Context, pool *sql.DB, q *database.Queries, tick time.Duration) {
	if tick <= 0 {
		tick = 24 * time.Hour
	}
	ticker := time.NewTicker(tick)
	go func() {
		defer ticker.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				ProcessLoanEMI(ctx, pool, q)
			}
		}
	}()
}
